export default function Help() {
  const t = useT();
  const { user } = useAuth();
  const [role, setRole] = useState(user.role);
  const [open, setOpen] = useState(0);
  const [benefits, setBenefits] = useState(false);
  return (
    <div>
      <h2 className="page-title">❓ {t('मदत व प्रशिक्षण')}</h2>
      <TrainingVideo />
      <div className="tabs">
        {Object.keys(GUIDES).map((r) => <button key={r} className={!benefits && role === r ? 'active' : ''} onClick={() => { setRole(r); setOpen(0); setBenefits(false); }}>{t(ROLE_NAME[r])}</button>)}
        <button className={benefits ? 'active' : ''} onClick={() => setBenefits(true)}>⭐ {t('फायदे व टिप्स')}</button>
      </div>
      {benefits && BENEFITS.map(([icon, title, items]) => (
        <div key={title} className="card">
          <h3 className="card-title">{icon} {t(title)}</h3>
          <ul className="help-steps benefit-list">{items.map((s) => <li key={s}>{t(s)}</li>)}</ul>
        </div>
      ))}
      {!benefits && GUIDES[role].map(([title, steps], i) => (
        <div key={title} className="card help-card">
          <button className="help-q" onClick={() => setOpen(open === i ? -1 : i)}>{t(title)}<span>{open === i ? '−' : '+'}</span></button>
          {open === i && <ol className="help-steps">{steps.map((s) => <li key={s}>{t(s)}</li>)}</ol>}
        </div>
      ))}
      <div className="card">
        <b>📞 {t('अडचण आल्यास')}</b>
        <p className="muted">{t('तुमच्या सुपरवायझरला "संपर्क" मधून फोन करा किंवा IT कक्षाशी संपर्क साधा.')}</p>
      </div>
    </div>
  );
}
